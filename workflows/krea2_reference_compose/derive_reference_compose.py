BASES = {"krea2_reference_compose": "krea2_image_edit", "krea2_reference_compose_nsfw": "krea2_image_edit_nsfw"}

SOURCE_HEAD = """# ─── Source ───────────────────────────────────────────────────────────────────
# {what} - the graph of {base} (Krea 2 Identity Edit by conradlocke / lbouaraba:
#   https://github.com/lbouaraba/comfyui-krea2edit (nodes, Apache-2.0)
#   https://huggingface.co/conradlocke/krea2-identity-edit (LoRA v1.2, Krea 2 Community License)
# on the {stack}), declared as ref2i: the sampler starts from an EMPTY latent of width x height, Picture 1 and
# Picture 2 only condition it, so the camera is free while the place of Picture 1 and the person of Picture 2 stay.
# Dynamic catalog LoRAs go into the Power Lora Loader (node 15) after the baked ones.
#
# GENERATED by krea2_reference_compose/derive_reference_compose.py from {base} - change that bundle and re-run
# it, never edit this one by hand (its e2e-test.ts is the exception).
#
"""

FINDINGS = """# ─── Findings (LORA_SPIKE.md #7, 2026-11) ─────────────────────────────────────
# - Plate (Picture 1) + ONE identity reference (Picture 2) with the Krea 2 Camera Angles v2 LoRA (catalog
#   krea2_camera_angles, loaded by the keyframe renderer): a real but MODEST lowering of the camera in the same
#   room with the same person (low angle: lens at tabletop height). Words alone moved the camera far less.
# - The angle phrase leads the prompt (`low angle shot, ...`, `high angle shot from behind, ...`): the LoRA's caption order.
# - A pure edit graph (no empty latent) pins Picture 1's camera - that is why this is a separate bundle.
# - Krea 2 Identity Edit takes ONE identity picture: two people as one side-by-side Picture 2 work for simple scenes only;
#   a shot with more people belongs to flux2_reference_compose.
# - The Camera Angles LoRA is RentCivit-only (licence): a production use needs the author's permission.
# ──────────────────────────────────────────────────────────────────────────────

"""

DESC = """description: >
  Generates a NEW image from a text prompt with Krea 2 {stack_short}, conditioned on a place picture (Picture 1)
  and optionally ONE person picture (Picture 2): the place and the person are kept, the CAMERA is free. It is not an
  edit - the image is rendered from an empty latent at the requested width x height.
  Use for: a keyframe whose camera height or angle differs from the place picture's (low angle, high angle, from
  behind): put the angle phrase FIRST in the prompt ("low angle shot, ...") and load the krea2_camera_angles LoRA.
  Not for: an in-place edit of a photo (use {edit}), a shot with more than one person to place or a plain
  shot at the place picture's own camera (use {flux}), text-to-image without a place or video.
"""

CONTEXT = """context: >
  Use for: a keyframe whose camera height or angle differs from the place picture's. Picture 1 = the place (the
  location plate), Picture 2 = ONE person (a character design); both only condition the render (Picture 2 is optional, an absent one is pruned), the output
  starts from an empty latent, so the camera comes from the prompt.
  Not for: an in-place edit of a photo (use {edit}), several people (use {flux}), a plain shot at the plate's own camera.

  Word the prompt with the ANGLE PHRASE FIRST and no other camera words: "low angle shot, <the person> from image 2 in the
  place of image 1, ..." or "high angle shot from behind, ...". Say what to keep: the room and its fixed items of image 1,
  the exact face, hair and build of image 2. The krea2_camera_angles LoRA (catalog) does the lowering / raising; without
  it the words alone move the camera only a little. Two people in one Picture 2 swap unreliably - give ONE person. Frame
  people large: small figures barely take the identity. ~2 min per image on l40s.

"""


def must_replace(text: str, old: str, new: str, count: int = 1) -> str:
    if text.count(old) != count:
        raise SystemExit(f"expected {count}x, found {text.count(old)}x: {old[:70]!r}")
    return text.replace(old, new)


def replace_span(text: str, start: str, end: str, new: str) -> str:
    a = text.find(start)
    b = text.find(end, a + 1)
    if a < 0 or b < 0:
        raise SystemExit(f"span markers not found: {start[:40]!r} .. {end[:40]!r}")
    return text[:a] + new + text[b:]


for name, base in BASES.items():
    nsfw = name.endswith("_nsfw")
    src, dst = LIB / base, LIB / name
    dst.mkdir(exist_ok=True)
    graph = json.loads((src / "workflow.json").read_text())
    graph["52"]["inputs"]["filename_prefix"] = name
    (dst / "workflow.json").write_text(json.dumps(graph, indent=1))

    y = (src / "workflow.yaml").read_text()
    stack = "Krea 2 NSFW realism stack" if nsfw else "Krea 2 realism stack"
    y = replace_span(
        y, "# ─── Source", "# ─── Custom Nodes",
        SOURCE_HEAD.format(what=name, base=base, stack=stack),
    )
    y = replace_span(y, "# ─── Findings", "name:", FINDINGS)
    y = must_replace(y, f"name: {base}\n", f"name: {name}\n")
    edit = "krea2_image_edit_nsfw" if nsfw else "krea2_image_edit"
    flux = "flux2_reference_compose_nsfw" if nsfw else "flux2_reference_compose"
    y = replace_span(
        y, "description: >", "url: workflow.json",
        DESC.format(stack_short="NSFW realism (nudity allowed)" if nsfw else "realism", edit=edit, flux=flux),
    )
    y = must_replace(y, "workflow_type: i2i\n", "workflow_type: ref2i\n")
    # `reference-compose` is not a declarable capability: a ref2i workflow IS one (`effectiveCapabilities()`), so no line
    y = y.replace("capabilities: [multi-reference-edit, staging-draft]\n", "")
    y = y.replace("capabilities: [multi-reference-edit]\n", "")
    if "capabilities:" in y:
        raise SystemExit("capabilities line left over")
    p1_start, p1_end = "      description: \"Picture 1, the image to edit", "\"\n      binding: image@20"
    y = replace_span(
        y, p1_start, p1_end,
        "      description: \"Picture 1, the PLACE: the location plate (a published location picture) whose room, fixed items and light are kept; its camera is NOT - the camera comes from the prompt. Around 1 MP works best.",
    )
    y = replace_span(
        y, "      description: \"Optional Picture 2, the identity reference", "\"\n      binding: image@21",
        "      description: \"Optional Picture 2, the identity reference: ONE person (character design) whose face, hair, skin and build are composed into the place. Leave it out for a place without a person.",
    )
    y = replace_span(
        y, "      description: \"Plain-English edit instruction", "\"\n      binding: prompt@40",
        "      description: \"Plain-English prompt that STARTS with the angle phrase (\\\"low angle shot, \\\" / \\\"high angle shot from behind, \\\"), then says who stands where in the place, e.g. \\\"low angle shot, the woman from image 2 stands at the window of the room of image 1, looking out. Keep the room and its fixed items of image 1 and the exact face, hair and build of image 2.\\\"",
    )
    y = must_replace(
        y, "      default: \"Place the adult person from image 2 into image 1. Keep the room, the lighting and the camera angle of image 1 and the exact face, hair and body of image 2.\"",
        "      default: \"The adult person from image 2 stands in the room of image 1. Keep the room, its fixed items and the lighting of image 1 and the exact face, hair and body of image 2.\"",
    )
    y = replace_span(
        y, "    - name: edited_image\n", "      node_id: \"52\"",
        "    - name: image\n      kind: image\n      description: \"The composed image.\"\n",
    )
    context = CONTEXT.format(edit=edit, flux=flux)
    if nsfw:
        context = context.replace(
            "Frame\n  people large:",
            "Nudity allowed (the KNPV + filter-bypass LoRAs are baked in; call every person an adult). An explicit act does not\n  come out of this graph (see krea2_image_edit_nsfw). Frame people large:",
        )
    y = replace_span(y, "context: >", "models:", context)
    (dst / "workflow.yaml").write_text(y)
    print("wrote", dst)
