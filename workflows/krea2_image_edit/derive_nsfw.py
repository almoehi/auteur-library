def must_replace(text: str, old: str, new: str, count: int = 1) -> str:
    if text.count(old) != count:
        raise SystemExit(f"expected {count}x, found {text.count(old)}x: {old[:70]!r}")
    return text.replace(old, new)


def replace_span(text: str, start: str, end: str, new: str) -> str:
    """Replace [start, end) with `new`; both markers must exist."""
    a = text.find(start)
    b = text.find(end, a + 1)
    if a < 0 or b < 0:
        raise SystemExit(f"span markers not found: {start[:40]!r} .. {end[:40]!r}")
    return text[:a] + new + text[b:]


