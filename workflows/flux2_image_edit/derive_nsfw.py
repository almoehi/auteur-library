"""Derive flux2_image_edit_nsfw from the SFW flux2_image_edit bundle.

The NSFW variant = the SFW graph + the general NSFW LoRA (SNOFS v1.4, 0.7) baked into the Power Lora
Loader, its model entry, `content: nsfw` and the NSFW wording. Re-run after every change to the SFW
bundle (the e2e-test.ts of the NSFW bundle is hand-written and not touched):

    python3 workflows/flux2_image_edit/derive_nsfw.py workflows
"""
import json
import pathlib
import re
import sys

LIB = pathlib.Path(sys.argv[1])
BASE = "flux2_image_edit"
LORA_NODE = "150"
BAKED = {"lora_snofs": {"on": True, "lora": "klein_snofs_v1_4.safetensors", "strength": 0.7}}
MODEL = """
  # CivitAI blocks datacenter IPs, so the CivitAI-sourced NSFW LoRA comes from the model-cache mirror.
  - name: klein_snofs_v1_4
    type: lora
    files:
      - url: https://s3.us-east-1.amazonaws.com/auteur-model-cache-20260905193718168400000001/public/lora/512c7f1d8dc7fa5dbc1fee6049c2975ef3007300a5de1712b3e1773cb95089f7/klein_snofs_v1_4.safetensors
        filename: klein_snofs_v1_4.safetensors
        sha256: 512c7f1d8dc7fa5dbc1fee6049c2975ef3007300a5de1712b3e1773cb95089f7
"""


def must_replace(text: str, old: str, new: str, count: int = 1) -> str:
    if old not in text:
        raise SystemExit(f"not found: {old[:70]!r}")
    return text.replace(old, new, count)


src, dst = LIB / BASE, LIB / f"{BASE}_nsfw"
dst.mkdir(exist_ok=True)
graph = json.loads((src / "workflow.json").read_text())
graph[LORA_NODE]["inputs"].update(BAKED)
(dst / "workflow.json").write_text(json.dumps(graph, indent=2, ensure_ascii=False) + "\n")

y = (src / "workflow.yaml").read_text()
head_start, head_end = y.index("# ─── Source"), y.index("# ─── Custom Nodes")
y = (y[:head_start] + "# ─── Source ───────────────────────────────────────────────────────────────────\n"
     f"# NSFW variant of {BASE}: the same graph and ports with the general NSFW LoRA (SNOFS v1.4, 0.7)\n"
     f"# baked into the Power Lora Loader. Generated by {BASE}/derive_nsfw.py - change {BASE} and\n"
     f"# re-run it, never edit this bundle by hand. Sources and node notes: see {BASE}.\n"
     "#\n" + y[head_end:])
y = must_replace(y, f"name: {BASE}\n", f"name: {BASE}_nsfw\n")
# The "Use for / Not for" alternatives in the description name SFW bundles; point them at their NSFW variants.
_d0, _d1 = y.index("\ndescription:"), y.index("\nurl: workflow.json\n")
_c0 = y.index("\ncontext:")
_c1 = y.index("\n\n", _c0)  # the Use for / Not for block opens the context
_alt = lambda s: re.sub(r"\b(flux2_image_edit|flux2_reference_compose|flux2_masked_inpaint|krea2_image_edit)\b(?!_nsfw)", r"\1_nsfw", s)
y = y[:_d0] + _alt(y[_d0:_d1]) + y[_d1:_c0] + _alt(y[_c0:_c1]) + y[_c1:]
y = must_replace(y, "\nmodel_family: flux2\n", "\nmodel_family: flux2\ncontent: nsfw\n")
y = must_replace(y, "\nurl: workflow.json\n",
                 "\n  NSFW variant: edits that undress or restage people - nudity and sex between adults allowed (a general\n"
                 "  NSFW LoRA is baked in; catalog edit LoRAs such as the 0x7 'no face change' nudity LoRA go on the ports).\n"
                 "url: workflow.json\n")
y = must_replace(y, "(model family flux2, trained for FLUX.2 Klein 9B: style, character, detail)",
                 "(model family flux2, trained for FLUX.2 Klein 9B: edit, act, detail)", count=4)
y = must_replace(y, "  LoRAs: up to four flux2 catalog LoRAs on lora_1..lora_4",
                 "  NSFW: the general NSFW LoRA SNOFS (0.7) is baked in - never select it on a port. To undress a person\n"
                 "  while keeping identity, put a keep-identity edit LoRA from the catalog on a port\n"
                 "  (flux2_nsfw_edit_nudity, flux2_nsfw_edit_female_nudity). Explicit acts compose better from the place and\n"
                 "  the characters with flux2_reference_compose_nsfw. Call every person an adult.\n"
                 "  LoRAs: up to four flux2 catalog LoRAs on lora_1..lora_4")
y = must_replace(y, "\nmodels:\n", "\nmodels:\n" + MODEL.lstrip("\n") + "\n")
(dst / "workflow.yaml").write_text(y)
print("wrote", dst)
