def load_templates() -> dict[str, dict[str, str]]:
    """gender -> panel -> asset name (path relative to the bundle). Content-hashed names: the asset URLs follow
    the loaded branch, so a changed template must get a new name, never overwrite the old file."""
    templates: dict[str, dict[str, str]] = {}
    for f in sorted((HERE / "assets").glob("*/*.png")):
        panel, digest = f.stem.rsplit("_", 1)
        if hashlib.sha256(f.read_bytes()).hexdigest()[:16] != digest:
            raise SystemExit(f"{f}: name hash does not match its content - rename it to {panel}_<sha256[:16]>.png")
        templates.setdefault(f.parent.name, {})[panel] = f.relative_to(HERE).as_posix()
    return templates


